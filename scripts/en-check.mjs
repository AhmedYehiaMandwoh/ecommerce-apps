// English (LTR) RN app check: language persistence, direction, labels, shop photos. 390x727 from scrollTop 0.
import { chromium } from '@playwright/test'; import fs from 'fs';
const APP = process.env.APP_URL || 'http://127.0.0.1:8082'; const O = (process.env.OUT || '/tmp/shots-en') + '/'; fs.mkdirSync(O, { recursive: true });
const b = await chromium.launch({ executablePath: process.env.CHROME_PATH, headless: true, args: ['--no-sandbox'] });
const p = await b.newPage({ viewport: { width: 390, height: 727 } });
let fail = 0; const ok = (c, m) => { console.log(c ? 'PASS' : 'FAIL', m); if (!c) fail++; };
const click = async (t) => { await p.getByRole('button', { name: t, exact: true }).first().click({ timeout: 8000 }); };
const dirOf = () => p.evaluate(() => document.documentElement.dir);
await p.goto(APP, { waitUntil: 'networkidle', timeout: 110000 }); await p.waitForTimeout(2500);
ok((await dirOf()) === 'rtl', 'default Arabic rtl');
await p.evaluate(() => localStorage.setItem('ghiyar-lang', 'en')); await p.reload({ waitUntil: 'networkidle' }); await p.waitForTimeout(3000);
ok((await dirOf()) === 'ltr', 'English ltr after reload (persisted)');
ok((await p.getByText('Start now').count()) > 0, 'splash labels English');
await p.screenshot({ path: O + 'en-01-splash.png' });
await click('Sign in'); await p.waitForTimeout(800); await p.screenshot({ path: O + 'en-02-phone.png' });
const phone = '01' + String(Date.now()).slice(-9);
await p.getByLabel('Mobile number').fill(phone); await click('Send the verification code ›'); await p.waitForTimeout(1500);
if (await p.getByLabel('Name', { exact: true }).count()) await p.getByLabel('Name', { exact: true }).first().fill('Test User');
await p.getByLabel('Verification code').first().fill('123456'); await click('Confirm the code ›'); await p.waitForTimeout(4500);
ok((await p.getByText('What are you looking for?').count()) > 0, 'home English');
await p.screenshot({ path: O + 'en-03-home.png' });
await click('Shops'); await p.waitForTimeout(2000); await p.screenshot({ path: O + 'en-04-shops.png' });
ok((await p.getByText('Demo photo').count()) > 0, 'shop list shows photos with demo label (English)');
await click('My account'); await p.waitForTimeout(800); await p.screenshot({ path: O + 'en-05-account.png' });
await click('App settings'); await p.waitForTimeout(800); await p.screenshot({ path: O + 'en-06-settings.png' });
ok((await p.getByText('Language').count()) > 0, 'settings has language');
await p.getByRole('button', { name: 'العربية', exact: true }).first().click(); await p.waitForTimeout(3500);
ok((await dirOf()) === 'rtl', 'switch back to Arabic rtl');
await b.close(); console.log(fail ? 'FAILED ' + fail : 'ALL PASS'); process.exit(fail ? 1 : 0);
